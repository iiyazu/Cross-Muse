def extra_mcp(agent: dict) -> list[dict]:
    """Validated `extra_mcp` entries of an agent's settings: [{name, command, args?, env?}]."""
    s = agent.get("settings") or {}
    raw = (json.loads(s) if isinstance(s, str) else s).get("extra_mcp", [])
    out = []
    for x in raw:
        name = x.get("name", "")
        if not (name.replace("-", "").replace("_", "").isalnum() and name != "xmuse" and isinstance(x.get("command"), str)
                and all(isinstance(a, str) for a in x.get("args", []))
                and all(isinstance(k, str) and isinstance(v, str) for k, v in x.get("env", {}).items())):
            raise ValueError(f"bad extra_mcp entry: {x!r}")
        out.append(x)
    return out


def overlay(agent: dict, state: Path, mcp: bool = True) -> str:
    """The per-run --patch file. JSON is valid YAML, so no YAML writer is needed."""
    provider, model = agent["model"].split("/", 1)
    rows: list = [{"id": "agent-default-model", "name": "@deepseek-ai/dsh-agent-default-model",
                   "config": {"provider": provider, "model": model}}]
    if provider in PI_AI_PROVIDERS:
        rows.insert(0, {"id": "llm-pi-ai", "name": "@deepseek-ai/dsh-llm-pi-ai", "config": {
            "providers": {provider: {"apiKeyEnv": PI_AI_PROVIDERS[provider]}}}})
    if mcp:
        rows.append({"insert": [{"id": "mcp-xmuse", "name": "@deepseek-ai/dsh-mcp-client", "config": {
            "serverName": "xmuse", "transport": "stdio", "command": "node", "args": [to_win(SHIM)],
            "env": {"XMUSE_STATE": to_win(state), "XMUSE_AGENT": agent["id"]}, "failOnStartupError": True}}]})
        # per-agent extra stdio MCP servers (`xmuse agent add --extra-mcp`), e.g. a test runner the sandboxed shell
        # cannot reach; MCP servers dsh starts run outside its worker sandbox, so only mount narrow, fixed-purpose ones
        for x in extra_mcp(agent):
            rows.append({"insert": [{"id": f"mcp-{x['name']}", "name": "@deepseek-ai/dsh-mcp-client", "config": {
                "serverName": x["name"], "transport": "stdio", "command": x["command"], "args": x.get("args", []),
                "env": x.get("env", {}), "failOnStartupError": True}}]})
    rows += [{"id": r, "disabled": True} for r in DISABLE]
    return json.dumps(rows, indent=1)


def scan_line(line: str):
    """One NDJSON line -> (kind, text) for live progress: ("tool", name), ("text", fragment) or ("final", text).
    None for anything else. Pure: unit-tested, reused by the run loop below."""
    if not line.startswith("{"):
        return None
    try:
        o = json.loads(line)
    except ValueError:
        return None
    typ = o.get("type")
    if typ == "tool_call" and isinstance(o.get("tool"), str):
        return ("tool", o["tool"])
    if typ == "text" and isinstance(o.get("text"), str):
        return ("text", o["text"])
    if typ == "final" and isinstance(o.get("text"), str):
        return ("final", o["text"])
    return None


def parse(lines) -> tuple[dict, Usage]:
    """--json NDJSON of one run -> (info, usage). step_end usage is per step; dsh never reports cache writes.
    info["reply"] is the run's last assistant text (H13)."""
    info, u = {}, Usage()
    for line in lines:
        if not line.startswith("{"):
            continue
        o = json.loads(line)
        typ = o.get("type")
        if typ == "session":
            info["session"] = o.get("sessionId")
        elif typ == "error":
            msg = o.get("message", "")
            info["error"] = msg
            info["owned"], info["unknown"] = OWNED in msg, UNKNOWN in msg
        elif typ == "tool_call" and o.get("tool") in CODE_TOOLS:
            u.mode = "code"
            info["active"] = True
        elif typ in ("tool_call", "tool_result", "text", "final"):
            info["active"] = True  # the agent already acted or spoke: a failure now is not a failed launch
            if typ in ("text", "final") and isinstance(o.get("text"), str):
                info["reply"] = o["text"]
        elif typ == "status" and o.get("phase") == "step_end" and o.get("usage"):
            s = o["usage"]
            u.input += s.get("inputTokens", 0)
            u.cache_read += s.get("cacheReadTokens", 0)
            u.output += s.get("outputTokens", 0)
            u.context = s.get("inputTokens", 0) + s.get("cacheReadTokens", 0)
            u.calls += 1
        elif typ == "status" and o.get("phase") == "turn_end":
            r = o.get("reason") or {}
            info["ok"] = r.get("kind") == "completed"
            if not info["ok"]:
                e = r.get("error") or {}
                info["error"] = f"{e.get('code', r.get('kind'))}: {e.get('message', '')}"
    return info, u


def human_turn(log: Path) -> bool:
    """A desktop-typed message (source.rpcId) with no turn/end after it.

    Fallback for presence() when no hook was ever seen for the session. Also kept for the
    unit test.
    """
    if not log.exists():
        return False
    busy = False
    raw = zstandard.ZstdDecompressor().stream_reader(log.open("rb")).read().decode()
    for line in raw.splitlines():
        o = json.loads(line)
        if o.get("type") == "user/message" and ((o.get("data") or {}).get("source") or {}).get("rpcId"):
            busy = True
        elif o.get("type") == "turn/end":
            busy = False
    return busy


def hooks_owner(ws: Path) -> str | None:
    """The dsh agent the workspace .dsh/hooks.json reports for (last argv word of its commands), if any."""
    try:
        hooks = json.loads((ws / ".dsh" / "hooks.json").read_text(encoding="utf-8"))["hooks"]
        return next(iter(hooks.values()))[0]["hooks"][0]["command"].split()[-1]
    except (OSError, ValueError, KeyError, IndexError, StopIteration, AttributeError):
        return None


def _is_headless_dsh(state: Path, agent_id: str) -> bool:
    conn = db.connect(state / "hub.db")
    try:
        a = db.row(conn.execute("select * from agents where id=? and vendor='dsh'", (agent_id,)))
    finally:
        conn.close()
    return a is not None and not db.settings(a).get("foreground")


class DshHeadless:
    name = "dsh"

    def __init__(self, sink, state: Path, cfg: dict):
        self.sink, self.state = sink, state
        self.exe = cfg.get("dsh_exe") or str(host.win_home() / APP / "DeepSeek Harness.exe")
        self.clijs = cfg.get("dsh_clijs") or to_win(host.win_home() / APP) + "\\" + CLIJS
        self.backoff, self.refusals = cfg.get("dsh_backoff", 10), cfg.get("dsh_refusals", 4)
        self.retry_wait = cfg.get("dsh_retry_wait", 3)  # seconds before the one launch retry
        self.first_event = cfg.get("dsh_first_event_timeout_s", 180)  # 0 disables the watchdog
        self.runs: dict[int, dict] = {}

    def command(self, patch: Path, session: str | None) -> list[str]:
        return [*proc.argv(self.exe), "--expose-internals", self.clijs, "--profile", "headless", "--patch", to_win(patch),
                "--json", *(["--session-id", session] if session else []), "-"]  # task text on stdin

    @staticmethod
    def launch_failed(info: dict) -> bool:
        """Exited non-zero before the agent did anything (exit 1 with empty stderr, TRANSPORT errors, a hang
        killed by the first-event watchdog). Unknown model / bad request / held session fail the same way
        next time, and a failure after the agent acted must never be replayed."""
        return (info.get("rc") != 0 and not info.get("active") and not info.get("owned") and not info.get("unknown")
                and "INVALID_REQUEST" not in info.get("error", ""))

    def run(self, cwd: Path, patch: Path, session: str | None, prompt: str, log: Path, st: dict | None = None,
            retry: bool = True, limit: float | None = None, turn_id: int | None = None):
        """One headless process; a failed launch is retried once, in place, with the same arguments.

        The retry lives here (below the engine) so the turn is still one turn: one prompt delivery, one turn
        record. Nothing the agent could have seen or done was lost, because `active` is still false.
        `limit` (seconds) kills a run that does not finish in time; only the precheck uses it."""
        info, usage = self._run_once(cwd, patch, session, prompt, log, st, limit, turn_id)
        if retry and self.launch_failed(info) and not (st and st["stop"].is_set()):
            log_ = logging.getLogger(__name__)
            log_.warning("dsh launch failed (%s); retrying once", info.get("error") or f"exit {info.get('rc')}")
            if st is not None:
                if st["stop"].wait(self.retry_wait):
                    return info, usage
            else:
                time.sleep(self.retry_wait)
            info, usage = self._run_once(cwd, patch, session, prompt, log, st, limit, turn_id)
        return info, usage

    def _run_once(self, cwd: Path, patch: Path, session: str | None, prompt: str, log: Path, st: dict | None,
                  limit: float | None = None, turn_id: int | None = None):
        got, hung, late = threading.Event(), threading.Event(), threading.Event()
        with log.open("a", encoding="utf-8") as out, log.with_suffix(".err").open("a", encoding="utf-8") as err:
            p = proc.popen(self.command(patch, session), cwd=cwd, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                           stderr=err, text=True, encoding="utf-8", env=clean_env(ENV))
            if st is not None:
                st["p"] = p

            def watchdog():  # no NDJSON line at all within the limit: the launch is stuck, not slow
                if not got.wait(self.first_event) and p.poll() is None:
                    hung.set()
                    proc.kill_tree(p)

            def overall():  # a precheck that started but never finishes (seen: step_start, then 10 min of silence)
                late.set()
                proc.kill_tree(p)

            if self.first_event:
                threading.Thread(target=watchdog, daemon=True).start()
            timer = threading.Timer(limit, overall) if limit else None
            if timer:
                timer.daemon = True
                timer.start()
            try:
                p.stdin.write(prompt)
                p.stdin.close()
            except OSError:  # died before reading its stdin (BrokenPipe): the exit code tells the story
                pass
            lines = []
            tools, last_tool, last_text = 0, None, ""
            for line in p.stdout:
                got.set()
                out.write(line)
                out.flush()
                lines.append(line)
                if turn_id is not None:
                    hit = scan_line(line)
                    if hit is not None:
                        if hit[0] == "tool":
                            tools += 1
                            last_tool = hit[1]
                        else:
                            last_text = hit[1]
                        self.sink.progress(turn_id, {"tools": tools, "last_tool": last_tool, "text": last_text})
            got.set()
        p.wait()
        if timer:
            timer.cancel()
        info, usage = parse(lines)
        info["rc"] = p.returncode
        if hung.is_set() and not lines:
            info["error"] = f"dsh produced no output within {self.first_event}s (killed)"
        if late.is_set() and p.returncode != 0:
            info["error"] = f"dsh did not finish within {limit}s (killed)"
        return info, usage

    def start(self, spec: TurnSpec) -> dict:
        patch = self.state / "runs" / f"turn-{spec.turn_id}.patch.yml"
        patch.write_text(overlay(spec.agent, self.state), encoding="utf-8")
        st = self.runs[spec.turn_id] = {"stop": threading.Event()}
        threading.Thread(target=self._turn, args=(spec, patch, st), daemon=True).start()
        return {"handle": spec.session, "cwd": to_win(spec.cwd)}

    def _turn(self, spec: TurnSpec, patch: Path, st: dict) -> None:
        delay, total = self.backoff, Usage()
        for attempt in range(self.refusals + 1):
            try:
                info, usage = self.run(spec.cwd, patch, spec.session, spec.prompt, spec.run_log, st,
                                    turn_id=spec.turn_id)
            except Exception as e:
                info, usage = {"error": f"start failed: {e}"}, Usage()
            total = usage if usage.calls else total
            if not info.get("owned") or attempt == self.refusals or st["stop"].wait(delay):
                break
            delay *= 2
        self.runs.pop(spec.turn_id, None)
        sid = info.get("session") or spec.session
        if st["stop"].is_set():
            end = TurnEnd(spec.turn_id, "interrupted", sid, total, "interrupted by hub")
        elif info.get("owned"):
            end = TurnEnd(spec.turn_id, "failed", sid, total, f"session {sid} held by another dsh process "
                                                             f"({self.refusals + 1} refusals)", requeue="hold")
        elif info.get("unknown"):
            end = TurnEnd(spec.turn_id, "failed", sid, total, info["error"], requeue="fresh")
        elif info.get("ok") and info.get("rc") == 0:
            end = TurnEnd(spec.turn_id, "succeeded", sid, total, reply=info.get("reply"))
        else:
            tail = spec.run_log.with_suffix(".err").read_text(encoding="utf-8")[-300:].strip() if spec.run_log.with_suffix(
                ".err").exists() else ""
            end = TurnEnd(spec.turn_id, "failed", sid, total, info.get("error") or f"exit {info.get('rc')}: {tail}")
        total.model = spec.agent["model"].split("/", 1)[1]
        self.sink.turn_ended(end)

    def interrupt(self, turn_id: int) -> None:
        st = self.runs.get(turn_id)
        if not st:
            return
        st["stop"].set()
        if st.get("p") and st["p"].poll() is None:
            proc.kill_tree(st["p"])  # the lease dies with the process (M0-dsh crash tests)


class DshDriver:
    vendor = "dsh"
    push = None  # no local push path into a live desktop session (gateway client is out of scope)

    def __init__(self, sink, state: Path, cfg: dict):
        self.state, self.ws = state, Path(cfg["workspace"])
        self.home = Path(cfg.get("dsh_home") or host.win_home() / ".dsh")
        self.headless = DshHeadless(sink, state, cfg)
        self.db = sink.db  # the engine's pool: hook reports and presence share one thread each
        self.cfg = cfg
        self.human: dict[str, float] = {}  # vendor session -> UserPromptSubmit report time
        self.seen: set[str] = set()  # vendor sessions ever reported by hooks (live state wins)

    def presence(self, agent: dict, session: str | None) -> Presence:
        if session and session in self.seen:
            ts = self.human.get(session)
            if ts is not None and time.time() - ts <= self.cfg.get("turn_timeout", 1800):
                return Presence("free", True, False)
            if ts is not None:  # Stop never arrived (desktop closed mid-turn): expire loudly
                self.human.pop(session, None)
                log.warning("dsh human flag for %s on %s expired after %ds without Stop; clearing",
                            agent["id"], session, int(time.time() - ts))
            return Presence("free", False, False)
        # no hook was ever seen for this session (desktop bridge not mounted): fall back
        # to the session log (M1b behaviour).
        logs = list(self.home.glob(f"sessions/*/{session}/session.v4.jsonl.zstd")) if session else []
        return Presence("free", bool(logs) and human_turn(logs[0]), False)

    def precheck(self, agent: dict, ws: Path) -> str | None:
        """One minimal run without tools: an unknown model or provider fails here (about 10 s, no tokens)."""
        patch = self.state / "runs" / f"precheck-{agent['id']}.patch.yml"
        patch.write_text(overlay(agent, self.state, mcp=False), encoding="utf-8")
        log = self.state / "logs" / f"precheck-{agent['id']}.jsonl"
        err = None
        for attempt in (0, 1):  # one retry: dsh headless sometimes exits 1 (empty stderr) on a cold start
            info, _ = self.headless.run(ws, patch, None, "Reply with the single word OK.", log, retry=False,
                                        limit=self.cfg.get("dsh_precheck_timeout_s", 120))
            if info.get("ok") and info["rc"] == 0:
                return None
            err = info.get("error") or f"exit {info['rc']}"
            if attempt or info.get("unknown") or "INVALID_REQUEST" in err or "unknown" in err.lower():
                break  # an unknown model or provider fails the same way again
            time.sleep(self.headless.retry_wait)
        return err

    def on_hook(self, agent: dict, event: str, p: dict) -> bool:
        """Live hook report from dsh_hook.py: {event, session_id, cwd, prompt, source, ...}.

        SessionStart adopts a desktop-opened session as current; UserPromptSubmit marks a
        human turn in flight (hub-owned wakepack prompts are ignored); Stop clears it.
        Every report marks its session seen: from then on the live state is authoritative
        and the session log is no longer read for it. Returns True when admission should
        be re-checked.
        """
        sid = p.get("session_id")
        if sid:
            self.seen.add(sid)
        if event == "SessionStart":
            if sid:
                self._adopt(agent["id"], sid, p.get("cwd"))
            return True
        if event == "UserPromptSubmit":
            if not sid or str(p.get("prompt", "")).lstrip().startswith(HUB_PROMPT_MARK):
                return False
            self.human[sid] = time.time()
            return True
        if event == "Stop":
            if sid:
                self.human.pop(sid, None)
            return True
        return False

    def _adopt(self, agent_id: str, sid: str, cwd: str | None) -> None:
        """A desktop-opened session becomes the agent's current one: the hub continues it after."""
        with db.tx(self.db()):
            cur = db.row(self.db().execute("select * from sessions where agent_id=? and state='current'",
                                           (agent_id,)))
            if cur and cur["vendor_session"] == sid:
                return
            if cur:
                self.db().execute("update sessions set state='retired', retired_at=? where id=?",
                                  (db.now(), cur["id"]))
            old = db.row(self.db().execute("select * from sessions where agent_id=? and vendor_session=?",
                                           (agent_id, sid)))
            if old:
                self.db().execute("update sessions set state='current', retired_at=null where id=?", (old["id"],))
            else:
                self.db().execute("insert into sessions(agent_id, vendor_session, cwd, origin, created_at)"
                                  " values(?,?,?,?,?)", (agent_id, sid, cwd, "tui", db.now()))

    @staticmethod
    def write_config(ws: Path, agent: dict, state: Path) -> list[Path]:
        """Workspace hooks.json + reporter copy for the desktop app (probe hooks-winws.json).

        The headless overlay intentionally does NOT mount the bridge: hub-owned prompts must
        never look human. The desktop profile mounts `@deepseek-ai/dsh-hooks-claude-code`
        with configPath at the hooks.json written here; its UserPromptSubmit/Stop reports
        then drive presence() live. Commands are workspace-relative (hook processes run in
        the session cwd); the hub state is baked in as a Windows path, the agent as argv.
        Skill and AGENTS.md still come from init.
        """
        d = ws / ".dsh"
        fg = db.settings({"settings": agent.get("settings")}).get("foreground")
        _set_block(ws / "AGENTS.md", FG_BEGIN.format(id=agent["id"]), FG_END.format(id=agent["id"]),
                   fg and foreground_section(ws, agent))
        if fg:
            # A foreground agent lives in a desktop session the hub must never adopt or continue: the presence
            # hooks would register it as the agent's current session, so none are written (and stale ones go).
            (ws / ".xmuse-tmp").mkdir(exist_ok=True)
            for f in ("hooks.json", "xmuse-dsh-hook.py"):
                (d / f).unlink(missing_ok=True)
            return []
        owner = hooks_owner(ws)
        if owner and owner != agent["id"] and _is_headless_dsh(state, owner):
            # One workspace hooks.json, so desktop-app presence follows one dsh agent: the first one added (T12).
            # Headless runs of the others carry their identity in the per-run overlay and need no hooks.
            return []
        d.mkdir(parents=True, exist_ok=True)
        if host.WINDOWS:  # the hub's own interpreter; there may be no python3 on a Windows PATH
            cmd = f'"{sys.executable}" .dsh/xmuse-dsh-hook.py {{ev}} "{state}" {agent["id"]}'
        else:
            cmd = f"python3 .dsh/xmuse-dsh-hook.py {{ev}} {to_win(state)} {agent['id']}"
        hooks = {"hooks": {ev: [{"hooks": [{"type": "command", "command": cmd.format(ev=ev)}]}]
                           for ev in ("SessionStart", "UserPromptSubmit", "Stop")}}
        (d / "hooks.json").write_text(json.dumps(hooks, indent=2) + "\n", encoding="utf-8")
        (d / "xmuse-dsh-hook.py").write_text(DSH_HOOK.read_text(encoding="utf-8"), encoding="utf-8")
        return [d / "hooks.json", d / "xmuse-dsh-hook.py"]

    def attach_command(self, agent: dict, session: str | None) -> str:
        return (f"dsh has no terminal UI: open the DeepSeek Harness desktop app"
                f"{' at session ' + session if session else ''} (workspace {to_win(self.ws)}).")

    def close(self) -> None:
        for t in list(self.headless.runs):
            self.headless.interrupt(t)
