"""Antigravity CLI (agy) wake adapter.

Mapping to the contract A–H (XMUSE2-ADAPTER-GUIDE §4):
  A  AgyHeadless.start / Sink.turn_ended      run headless turn; turn-end + failure events
  B  AgyDriver.write_config                    project-level .agents config + hooks.json
  C  AgyDriver.presence                        single writer: 'free' or 'tui'
  D  AgyDriver.push                            None (no live push path)
  E  TurnEnd.usage                             per-turn usage, never cumulative
  F  Presence.human_turn + AgyDriver.on_hook   tell human input from hub input
  G  AgyDriver.on_hook                         turn-boundary hooks (optional)
  H  agent["model"] + env.clean_env()          explicit model, clean environment
"""
