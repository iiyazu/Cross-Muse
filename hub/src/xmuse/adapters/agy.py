APP = "AppData/Local/agy/bin/agy.exe"
CODE_TOOLS = {"run_command", "write_to_file", "replace_file_content", "edit_file", "patch_file"}

# The PreToolUse gate (.agents/xmuse-hook.py): STATE, AGENT and WRITERS, then this. It asks the hub (POST /v1/risk,
# the agent's own token) and stays stdlib-only: agy may run it with any python. agy runs headless, so a command the
# user has to approve is denied with the reason, and the agent is told to ask the user through xmuse. When the hub
# cannot answer, the call is denied: the gate fails closed.
# Input (docs/adapters/agy.zh.md 1.5): {"tool_name", "tool_input": {"CommandLine", "Cwd", ...}, "workspace_paths"}.
HOOK_BODY = '''
import json
import os
import sys
import urllib.request


def _ask(body):
    hub = json.load(open(os.path.join(STATE, "hub.json"), encoding="utf-8"))
    token = open(os.path.join(STATE, "tokens", AGENT), encoding="utf-8").read().strip()
    req = urllib.request.Request("http://127.0.0.1:%d/v1/risk" % hub["port"], method="POST",
                                 data=json.dumps(body).encode(),
                                 headers={"authorization": "Bearer " + token, "content-type": "application/json"})
    reply = json.loads(urllib.request.urlopen(req, timeout=8).read())
    if "result" not in reply:
        raise RuntimeError((reply.get("error") or {}).get("message") or "no answer")
    return reply["result"].get("why")


def _main():
    try:
        req = json.load(sys.stdin)
    except Exception:
        req = {}
    tool = req.get("tool_name") or (req.get("toolCall") or {}).get("name") or ""
    args = req.get("tool_input") or (req.get("toolCall") or {}).get("args") or {}
    why = None
    try:
        if tool == "run_command":
            why = _ask({"command": str(args.get("CommandLine") or ""), "cwd": str(args.get("Cwd") or "")})
        elif tool in WRITERS:
            paths = [str(v) for k, v in args.items() if isinstance(v, str) and ("File" in k or "Path" in k)]
            why = _ask({"paths": paths})
    except Exception as e:
        why = "the xmuse gate could not check this (%s)" % e
    if why:
        print(json.dumps({"decision": "deny", "reason": "needs the user's approval: %s. Ask the user with "
                          "xmuse_send (to: human) and wait for the answer; do not try another way around." % why}))
    else:
        print(json.dumps({"decision": "allow"}))


_main()
'''
WRITERS = {"write_to_file", "replace_file_content", "edit_file", "patch_file", "multi_replace_file_content"}


def gate_script(agent_id: str, state: Path) -> str:
    """`state` as the agy process sees it (a Windows path when agy runs on Windows, like the MCP config's)."""
    return (f"# Auto-generated by xmuse for agent {agent_id}: the shell and file-write gate (auto mode)\n"
            f"STATE = {str(state)!r}\nAGENT = {agent_id!r}\nWRITERS = {sorted(WRITERS)!r}\n" + HOOK_BODY)


def _default_agy_bin() -> str | None:
    agy = shutil.which("agy")
    if agy:
        return agy
    try:
        p = host.win_home() / APP
        if p.exists():
            return str(p)
    except host.HostError:
        pass
    return None


def _succeeded(stdout_text: str) -> bool:
    """agy's final `result` event says SUCCESS."""
    for line in reversed(stdout_text.splitlines()):
        try:
            ev = json.loads(line)
        except ValueError:
            continue
        if isinstance(ev, dict) and ev.get("event") == "result":
            return (ev.get("result") or {}).get("status") == "SUCCESS"
    return False


def parse_transcript(path: Path) -> tuple[dict, Usage]:
    """Parse transcript.jsonl of one run -> (info, usage)."""
    info, u = {}, Usage()
    if not path.exists():
        return info, u
    for line in path.open(encoding="utf-8"):
        line = line.strip()
        if not line or not line.startswith("{"):
            continue
        try:
            o = json.loads(line)
        except Exception:
            continue
        src = o.get("source")
        typ = o.get("type")
        content = o.get("content", "")
        if typ == "PLANNER_RESPONSE" and src == "MODEL":
            u.calls += 1
            u.output += len(content) // 4
            calls = o.get("tool_calls") or []
            for call in calls:
                if (call.get("name") or "") in CODE_TOOLS:
                    u.mode = "code"
        elif typ == "USER_INPUT":
            u.input += len(content) // 4
    u.context = u.input + u.output
    return info, u


def scan_agy_line(acc: dict, line: str) -> bool:
    """Fold one stream-json line into a live progress accumulator (H4). True when tools or text changed."""
    if not line.startswith("{"):
        return False
    try:
        o = json.loads(line)
    except ValueError:
        return False
    changed = False
    ev = o.get("event")
    if ev == "step_update":
        su = o.get("step_update") or {}
        stype = su.get("step_type")
        if stype == "tool" and su.get("state") == "ACTIVE":
            acc["tools"] = acc.get("tools", 0) + 1
            acc["last_tool"] = su.get("tool_name") or ((su.get("tool_info") or {}).get("name", acc.get("last_tool")))
            changed = True
        elif stype == "agent_response":
            delta = su.get("text_delta")
            if delta and isinstance(delta, str):
                acc["text"] = acc.get("text", "") + delta
                changed = True
    return changed


def parse_stream(lines: list[str]) -> tuple[dict, Usage]:
    """stream-json of one `agy -p` run -> (result info, usage)."""
    info, u = {}, Usage()
    last_text = []
    seen_calls = 0
    for line in lines:
        if not line.startswith("{"):
            continue
        try:
            o = json.loads(line)
        except ValueError:
            continue
        ev = o.get("event")
        if ev == "init":
            if o.get("conversation_id"):
                info["session"] = o["conversation_id"]
        elif ev == "step_update":
            su = o.get("step_update") or {}
            stype = su.get("step_type")
            if stype == "tool":
                tname = su.get("tool_name") or ((su.get("tool_info") or {}).get("name") or "")
                if tname in CODE_TOOLS:
                    u.mode = "code"
            elif stype == "agent_response":
                delta = su.get("text_delta")
                if delta:
                    last_text.append(delta)
                if su.get("state") == "DONE":
                    seen_calls += 1
        elif ev == "result":
            res = o.get("result") or {}
            if res.get("conversation_id"):
                info["session"] = res["conversation_id"]
            info["ok"] = (res.get("status") == "SUCCESS")
            info["error"] = None if info["ok"] else (res.get("error") or res.get("status"))
            usg = res.get("usage") or {}
            u.input = usg.get("input_tokens", 0)
            u.output = usg.get("output_tokens", 0)
            u.cache_read = usg.get("cache_read_tokens", 0)
            u.context = usg.get("total_tokens", 0) or (u.input + u.output + u.cache_read)
            u.calls = max(res.get("num_turns", seen_calls or 1), 1)
            info["reply"] = res.get("response") or "".join(last_text)
            if res.get("denied_actions"):
                info["denied"] = [d.get("action") for d in res["denied_actions"] if isinstance(d, dict)]
    return info, u


class AgyHeadless:
    name = "agy"

    def __init__(self, sink, state: Path, cfg: dict):
        self.sink = sink
        self.state = state
        self.cfg = cfg
        self.bin = cfg.get("agy_bin") or _default_agy_bin() or "agy"
        self.runs: dict[int, dict] = {}

    def command(self, session: str | None, prompt: str, agent: dict | None = None) -> list[str]:
        # No proc.argv on main: inline the only case that needs wrapping (a .py fake on Windows has no shebang).
        if sys.platform == "win32" and str(self.bin).lower().endswith(".py"):
            cmd = [sys.executable, str(self.bin)]
        else:
            cmd = [str(self.bin)]
        if "--output-format" not in cmd:
            cmd.extend(["--output-format", "stream-json"])
        if "--dangerously-skip-permissions" not in cmd:
            cmd.append("--dangerously-skip-permissions")
        if session:
            cmd.append(f"--conversation={session}")
        s = db.settings(agent) if agent else {}
        effort = s.get("effort")
        if effort in ("low", "medium", "high", "xhigh", "max"):
            cmd.extend(["--effort", effort])
        cmd.extend(["-p", prompt])
        return cmd

    def start(self, spec: TurnSpec) -> dict:
        st = self.runs[spec.turn_id] = {"stop": threading.Event()}
        threading.Thread(target=self._turn, args=(spec, st), daemon=True).start()
        return {"handle": spec.session, "cwd": to_win(spec.cwd)}

    def _turn(self, spec: TurnSpec, st: dict) -> None:
        cmd = self.command(spec.session, spec.prompt, spec.agent)
        cwd = to_win(spec.cwd) if sys.platform == "win32" else spec.cwd
        env = clean_env({"CASCADE_DEFAULT_MODEL_OVERRIDE": spec.agent["model"]})
        sid = spec.session
        lines, stderr_text, rc = [], "", 0
        prog = {"tools": 0, "last_tool": None, "text": ""}

        with spec.run_log.open("a", encoding="utf-8") as out, spec.run_log.with_suffix(".err").open("a", encoding="utf-8") as err:
            try:
                p = subprocess.Popen(cmd, cwd=cwd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                     stderr=subprocess.PIPE, text=True, encoding="utf-8", env=env,
                                     start_new_session=True)
                st["p"] = p

                def _read_err():
                    nonlocal stderr_text
                    try:
                        stderr_text = p.stderr.read()
                        err.write(stderr_text)
                        err.flush()
                    except Exception:
                        pass

                t_err = threading.Thread(target=_read_err, daemon=True)
                t_err.start()

                for line in p.stdout:
                    out.write(line)
                    out.flush()
                    lines.append(line)
                    if scan_agy_line(prog, line):
                        self.sink.progress(spec.turn_id, dict(prog))

                p.wait()
                t_err.join(timeout=2)
                rc = p.returncode
            except Exception as e:
                rc = 1
                stderr_text = f"start failed: {e}"
                err.write(stderr_text)

        end = None
        try:
            info, stream_usage = parse_stream(lines)
            if info.get("session"):
                sid = info["session"]

            # Detect created conversation id if this was a fresh session and not found in stream
            if not sid:
                m = re.search(r"Created conversation ([0-9a-fA-F-]+)", "".join(lines) + stderr_text)
                if not m:
                    m = re.search(r"conversation=([0-9a-fA-F-]+)", "".join(lines) + stderr_text)
                if m:
                    sid = m.group(1)
                else:
                    last_convs = self._read_last_conversations()
                    sid = last_convs.get(str(cwd)) or last_convs.get(to_win(spec.cwd)) or f"session-{spec.turn_id}"

            # Only a turn agy did not report as a success is searched for these: the output carries tool results and
            # timings ("duration_seconds":0.082294294 once read as a 429 and paused a healthy agy for an hour).
            out_text = "".join(lines)
            full_output = "" if _succeeded(out_text) else (out_text + "\n" + stderr_text).strip().lower()
            is_unknown = "not found" in full_output or "does not exist" in full_output
            is_quota = re.search(r"resource_exhausted|quota|\b429\b", full_output) is not None

            # Determine usage
            if stream_usage.calls > 0:
                usage = stream_usage
            else:
                transcript_path = self._transcript_path(sid)
                if transcript_path and transcript_path.exists():
                    _, usage = parse_transcript(transcript_path)
                else:
                    usage = Usage()
                    usage.input = len(spec.prompt) // 4
                    usage.output = sum(len(l) for l in lines) // 4
                    usage.context = usage.input + usage.output
                    usage.calls = 1
                    if any(t in "".join(lines) for t in CODE_TOOLS):
                        usage.mode = "code"

            usage.model = spec.agent.get("model", "")
            reply = info.get("reply")

            note = None
            if info.get("denied"):
                note = "permission_denied: " + ", ".join(info["denied"])

            if st["stop"].is_set():
                end = TurnEnd(spec.turn_id, "interrupted", sid, usage, "interrupted by hub", note=note, reply=reply)
            elif is_unknown:
                end = TurnEnd(spec.turn_id, "failed", sid, usage, "conversation not found", note=note, requeue="fresh", reply=reply)
            elif is_quota:
                end = TurnEnd(spec.turn_id, "failed", sid, usage, "quota exceeded", note=note, retry_at=time.time() + 3600, reply=reply)
            elif rc == 0 and info.get("ok", True):
                end = TurnEnd(spec.turn_id, "succeeded", sid, usage, note=note, reply=reply)
            else:
                tail = stderr_text[-300:].strip() or (info.get("error") if info.get("error") else f"exit {rc}")
                end = TurnEnd(spec.turn_id, "failed", sid, usage, tail, note=note, reply=reply)
        except (Exception, host.HostError) as e:
            log.exception(f"turn {spec.turn_id} finalize failed: {e}")
            end = TurnEnd(spec.turn_id, "failed", sid or spec.session, Usage(), f"internal error: {e}")
        finally:
            self.runs.pop(spec.turn_id, None)
            if end is not None:
                self.sink.turn_ended(end)

    def _read_last_conversations(self) -> dict:
        candidates = [
            Path.home() / ".gemini/antigravity-cli/cache/last_conversations.json",
        ]
        try:
            candidates.append(host.win_home() / ".gemini/antigravity-cli/cache/last_conversations.json")
            candidates.append(host.win_home() / "AppData/Local/agy/cache/last_conversations.json")
        except (Exception, host.HostError):
            pass
        for p in candidates:
            try:
                if p.exists():
                    return json.loads(p.read_text(encoding="utf-8"))
            except (Exception, host.HostError):
                pass
        return {}

    def _transcript_path(self, sid: str | None) -> Path | None:
        if not sid:
            return None
        candidates = [
            Path.home() / f".gemini/antigravity-cli/brain/{sid}/.system_generated/logs/transcript.jsonl",
            Path.home() / f".gemini/antigravity/brain/{sid}/.system_generated/logs/transcript.jsonl",
        ]
        try:
            candidates.append(host.win_home() / f".gemini/antigravity-cli/brain/{sid}/.system_generated/logs/transcript.jsonl")
            candidates.append(host.win_home() / f".gemini/antigravity/brain/{sid}/.system_generated/logs/transcript.jsonl")
        except (Exception, host.HostError):
            pass
        for p in candidates:
            try:
                if p.exists():
                    return p
            except (Exception, host.HostError):
                pass
        return None

    def interrupt(self, turn_id: int) -> None:
        st = self.runs.get(turn_id)
        if not st:
            return
        st["stop"].set()
        if st.get("p") and st["p"].poll() is None:
            try:
                os.killpg(st["p"].pid, signal.SIGKILL)
            except ProcessLookupError:
                pass


class AgyDriver:
    vendor = "agy"
    push = None

    def __init__(self, sink, state: Path, cfg: dict):
        self.sink = sink
        self.state = state
        self.cfg = cfg
        self.headless = AgyHeadless(sink, state, cfg)

    def presence(self, agent: dict, session: str | None) -> Presence:
        return Presence("free", False, False)

    def on_hook(self, agent: dict, event: str, payload: dict) -> bool:
        return False

    def attach_command(self, agent: dict, session: str | None) -> str:
        return f"agy --conversation={session}" if session else "agy"

    def register_shim(self, agent: dict, p: dict) -> None:
        pass

    @staticmethod
    def write_config(ws: Path, agent: dict, state: Path) -> list[Path]:
        """Project-level config: .agents/plugins/xmuse MCP + hooks.json safety gate."""
        out = []
        plug_dir = ws / ".agents" / "plugins" / "xmuse"
        plug_dir.mkdir(parents=True, exist_ok=True)

        manifest = plug_dir / "plugin.json"
        manifest.write_text(json.dumps({"name": "xmuse"}, indent=2), encoding="utf-8")
        out.append(manifest)

        mcp_cfg = plug_dir / "mcp_config.json"
        is_win = sys.platform == "win32"
        mcp_data = {
            "mcpServers": {
                "xmuse": {
                    "command": "node",
                    "args": [to_win(SHIM) if is_win else str(SHIM)],
                    "env": {
                        "XMUSE_STATE": to_win(state) if is_win else str(state),
                        "XMUSE_AGENT": agent["id"],
                    },
                }
            }
        }
        mcp_cfg.write_text(json.dumps(mcp_data, indent=2), encoding="utf-8")
        out.append(mcp_cfg)

        hook_script = ws / ".agents" / "xmuse-hook.py"
        hook_script.write_text(gate_script(agent["id"], to_win(state) if is_win else state), encoding="utf-8")
        out.append(hook_script)

        hooks_cfg = ws / ".agents" / "hooks.json"
        hooks_data = {
            "xmuse-safety": {
                "PreToolUse": [
                    {
                        "matcher": "*",
                        "hooks": [
                            {
                                "type": "command",
                                "command": "python xmuse-hook.py" if is_win else "python3 xmuse-hook.py",
                            }
                        ],
                    }
                ]
            }
        }
        hooks_cfg.write_text(json.dumps(hooks_data, indent=2), encoding="utf-8")
        out.append(hooks_cfg)

        return out

    def close(self) -> None:
        pass
