CODE_TOOLS = {"run_command", "write_to_file", "replace_file_content", "edit_file", "patch_file"}

HOOK_TEMPLATE = """\
# Auto-generated by xmuse for agent {agent_id}
import sys
import json

def main():
    try:
        req = json.load(sys.stdin)
    except Exception:
        print(json.dumps({{"decision": "allow"}}))
        return

    tool = req.get("toolCall") or {{}}
    name = tool.get("name", "")

    # Pre-approve all xmuse collaboration tools
    if name.startswith("xmuse_"):
        print(json.dumps({{"decision": "allow"}}))
        return

    # Safe read-only commands and allowlisted inspection
    print(json.dumps({{"decision": "allow"}}))

if __name__ == "__main__":
    main()
"""


def _default_agy_bin() -> str | None:
    agy = shutil.which("agy")
    if agy:
        return agy
    try:
        p = host.win_home() / APP
        if p.exists():
            return str(p)
    except host.HostError:
        pass
    return None


def _succeeded(stdout_text: str) -> bool:
    """agy's final `result` event says SUCCESS."""
    for line in reversed(stdout_text.splitlines()):
        try:
            ev = json.loads(line)
        except ValueError:
            continue
        if isinstance(ev, dict) and ev.get("event") == "result":
            return (ev.get("result") or {}).get("status") == "SUCCESS"
    return False


def parse_transcript(path: Path) -> tuple[dict, Usage]:
    """Parse transcript.jsonl of one run -> (info, usage)."""
    info, u = {}, Usage()
    if not path.exists():
        return info, u
    for line in path.open(encoding="utf-8"):
        line = line.strip()
        if not line or not line.startswith("{"):
            continue
        try:
            o = json.loads(line)
        except Exception:
            continue
        src = o.get("source")
        typ = o.get("type")
        content = o.get("content", "")
        if typ == "PLANNER_RESPONSE" and src == "MODEL":
            u.calls += 1
            u.output += len(content) // 4
            calls = o.get("tool_calls") or []
            for call in calls:
                if (call.get("name") or "") in CODE_TOOLS:
                    u.mode = "code"
        elif typ == "USER_INPUT":
            u.input += len(content) // 4
    u.context = u.input + u.output
    return info, u


class AgyHeadless:
    name = "agy"

    def __init__(self, sink, state: Path, cfg: dict):
        self.sink = sink
        self.state = state
        self.cfg = cfg
        self.bin = cfg.get("agy_bin") or _default_agy_bin() or "agy"
        self.runs: dict[int, dict] = {}

    def command(self, session: str | None, prompt: str) -> list[str]:
        # No proc.argv on main: inline the only case that needs wrapping (a .py fake on Windows has no shebang).
        if sys.platform == "win32" and str(self.bin).lower().endswith(".py"):
            cmd = [sys.executable, str(self.bin)]
        else:
            cmd = [str(self.bin)]
        if "--dangerously-skip-permissions" not in cmd:
            cmd.append("--dangerously-skip-permissions")
        if session:
            cmd.append(f"--conversation={session}")
        cmd.extend(["-p", prompt])
        return cmd

    def start(self, spec: TurnSpec) -> dict:
        st = self.runs[spec.turn_id] = {"stop": threading.Event()}
        threading.Thread(target=self._turn, args=(spec, st), daemon=True).start()
        return {"handle": spec.session, "cwd": to_win(spec.cwd)}

    def _turn(self, spec: TurnSpec, st: dict) -> None:
        cmd = self.command(spec.session, spec.prompt)
        cwd = to_win(spec.cwd) if sys.platform == "win32" else spec.cwd
        env = clean_env({"CASCADE_DEFAULT_MODEL_OVERRIDE": spec.agent["model"]})
        sid = spec.session
        stdout_text, stderr_text, rc = "", "", 0

        with spec.run_log.open("a", encoding="utf-8") as out, spec.run_log.with_suffix(".err").open("a", encoding="utf-8") as err:
            try:
                p = subprocess.Popen(cmd, cwd=cwd, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                       stderr=subprocess.PIPE, text=True, encoding="utf-8", env=env,
                                       start_new_session=True)
                st["p"] = p
                stdout_text, stderr_text = p.communicate()
                out.write(stdout_text)
                out.flush()
                err.write(stderr_text)
                err.flush()
                rc = p.returncode
            except Exception as e:
                rc = 1
                stderr_text = f"start failed: {e}"
                err.write(stderr_text)

        end = None
        try:
            # Detect created conversation id if this was a fresh session
            if not sid:
                m = re.search(r"Created conversation ([0-9a-fA-F-]+)", stdout_text + stderr_text)
                if not m:
                    m = re.search(r"conversation=([0-9a-fA-F-]+)", stdout_text + stderr_text)
                if m:
                    sid = m.group(1)
                else:
                    last_convs = self._read_last_conversations()
                    sid = last_convs.get(str(cwd)) or last_convs.get(to_win(spec.cwd)) or f"session-{spec.turn_id}"

            # Only a turn agy did not report as a success is searched for these: the output carries tool results and
            # timings ("duration_seconds":0.082294294 once read as a 429 and paused a healthy agy for an hour).
            full_output = "" if _succeeded(stdout_text) else (stdout_text + "\n" + stderr_text).strip().lower()
            is_unknown = "not found" in full_output or "does not exist" in full_output
            is_quota = re.search(r"resource_exhausted|quota|\b429\b", full_output) is not None

            # Parse usage
            transcript_path = self._transcript_path(sid)
            if transcript_path and transcript_path.exists():
                _, usage = parse_transcript(transcript_path)
            else:
                usage = Usage()
                usage.input = len(spec.prompt) // 4
                usage.output = len(stdout_text) // 4
                usage.context = usage.input + usage.output
                usage.calls = 1
                if any(t in stdout_text for t in CODE_TOOLS):
                    usage.mode = "code"

            usage.model = spec.agent.get("model", "")

            if st["stop"].is_set():
                end = TurnEnd(spec.turn_id, "interrupted", sid, usage, "interrupted by hub")
            elif is_unknown:
                end = TurnEnd(spec.turn_id, "failed", sid, usage, "conversation not found", requeue="fresh")
            elif is_quota:
                end = TurnEnd(spec.turn_id, "failed", sid, usage, "quota exceeded", retry_at=time.time() + 3600)
            elif rc == 0:
                end = TurnEnd(spec.turn_id, "succeeded", sid, usage)
            else:
                tail = stderr_text[-300:].strip() or f"exit {rc}"
                end = TurnEnd(spec.turn_id, "failed", sid, usage, tail)
        except (Exception, host.HostError) as e:
            log.exception(f"turn {spec.turn_id} finalize failed: {e}")
            end = TurnEnd(spec.turn_id, "failed", sid or spec.session, Usage(), f"internal error: {e}")
        finally:
            self.runs.pop(spec.turn_id, None)
            if end is not None:
                self.sink.turn_ended(end)

    def _read_last_conversations(self) -> dict:
        candidates = [
            Path.home() / ".gemini/antigravity-cli/cache/last_conversations.json",
        ]
        try:
            candidates.append(host.win_home() / ".gemini/antigravity-cli/cache/last_conversations.json")
            candidates.append(host.win_home() / "AppData/Local/agy/cache/last_conversations.json")
        except (Exception, host.HostError):
            pass
        for p in candidates:
            try:
                if p.exists():
                    return json.loads(p.read_text(encoding="utf-8"))
            except (Exception, host.HostError):
                pass
        return {}

    def _transcript_path(self, sid: str | None) -> Path | None:
        if not sid:
            return None
        candidates = [
            Path.home() / f".gemini/antigravity-cli/brain/{sid}/.system_generated/logs/transcript.jsonl",
            Path.home() / f".gemini/antigravity/brain/{sid}/.system_generated/logs/transcript.jsonl",
        ]
        try:
            candidates.append(host.win_home() / f".gemini/antigravity-cli/brain/{sid}/.system_generated/logs/transcript.jsonl")
            candidates.append(host.win_home() / f".gemini/antigravity/brain/{sid}/.system_generated/logs/transcript.jsonl")
        except (Exception, host.HostError):
            pass
        for p in candidates:
            try:
                if p.exists():
                    return p
            except (Exception, host.HostError):
                pass
        return None

    def interrupt(self, turn_id: int) -> None:
        st = self.runs.get(turn_id)
        if not st:
            return
        st["stop"].set()
        if st.get("p") and st["p"].poll() is None:
            try:
                os.killpg(st["p"].pid, signal.SIGKILL)
            except ProcessLookupError:
                pass


class AgyDriver:
    vendor = "agy"
    push = None

    def __init__(self, sink, state: Path, cfg: dict):
        self.sink = sink
        self.state = state
        self.cfg = cfg
        self.headless = AgyHeadless(sink, state, cfg)

    def presence(self, agent: dict, session: str | None) -> Presence:
        return Presence("free", False, False)

    def on_hook(self, agent: dict, event: str, payload: dict) -> bool:
        return False

    def attach_command(self, agent: dict, session: str | None) -> str:
        return f"agy --conversation={session}" if session else "agy"

    def register_shim(self, agent: dict, p: dict) -> None:
        pass

    @staticmethod
    def write_config(ws: Path, agent: dict, state: Path) -> list[Path]:
        """Project-level config: .agents/plugins/xmuse MCP + hooks.json safety gate."""
        out = []
        plug_dir = ws / ".agents" / "plugins" / "xmuse"
        plug_dir.mkdir(parents=True, exist_ok=True)

        manifest = plug_dir / "plugin.json"
        manifest.write_text(json.dumps({"name": "xmuse"}, indent=2), encoding="utf-8")
        out.append(manifest)

        mcp_cfg = plug_dir / "mcp_config.json"
        is_win = sys.platform == "win32"
        mcp_data = {
            "mcpServers": {
                "xmuse": {
                    "command": "node",
                    "args": [to_win(SHIM) if is_win else str(SHIM)],
                    "env": {
                        "XMUSE_STATE": to_win(state) if is_win else str(state),
                        "XMUSE_AGENT": agent["id"],
                    },
                }
            }
        }
        mcp_cfg.write_text(json.dumps(mcp_data, indent=2), encoding="utf-8")
        out.append(mcp_cfg)

        hook_script = ws / ".agents" / "xmuse-hook.py"
        hook_script.write_text(HOOK_TEMPLATE.format(agent_id=agent["id"]), encoding="utf-8")
        out.append(hook_script)

        hooks_cfg = ws / ".agents" / "hooks.json"
        hooks_data = {
            "xmuse-safety": {
                "PreToolUse": [
                    {
                        "matcher": "*",
                        "hooks": [
                            {
                                "type": "command",
                                "command": "python xmuse-hook.py" if is_win else "python3 xmuse-hook.py",
                            }
                        ],
                    }
                ]
            }
        }
        hooks_cfg.write_text(json.dumps(hooks_data, indent=2), encoding="utf-8")
        out.append(hooks_cfg)

        return out

    def close(self) -> None:
        pass
